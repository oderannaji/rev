import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdtemp,mkdir,writeFile,readFile,copyFile,rm} from 'node:fs/promises';
import {join} from 'node:path';
import {tmpdir} from 'node:os';
import {execFile} from 'node:child_process';
import {promisify} from 'node:util';
import net from 'node:net';
const execute=promisify(execFile);
test('local updater fast-forwards staging, preserves data and refuses dirty work',async t=>{
  const dir=await mkdtemp(join(tmpdir(),'shepherd-update-'));t.after(()=>rm(dir,{recursive:true,force:true}));
  const seed=join(dir,'seed'),remote=join(dir,'remote.git'),checkout=join(dir,'checkout'),bin=join(dir,'bin'),log=join(dir,'npm.log');
  await mkdir(seed);await mkdir(bin);
  const git=(cwd,...args)=>execute('git',args,{cwd});
  await git(dir,'init','--bare',remote);await git(seed,'init','-b','staging');
  await git(seed,'config','user.name','Updater test');await git(seed,'config','user.email','test@example.invalid');
  await mkdir(join(seed,'scripts'));await copyFile(new URL('../scripts/update-local.sh',import.meta.url),join(seed,'scripts/update-local.sh'));
  await writeFile(join(seed,'.gitignore'),'node_modules/\n.local/\n');await writeFile(join(seed,'package-lock.json'),'{}\n');await writeFile(join(seed,'version.txt'),'one');
  await git(seed,'add','.');await git(seed,'commit','-m','Initial');await git(seed,'remote','add','origin',remote);await git(seed,'push','-u','origin','staging');
  await git(dir,'clone','--branch','staging',remote,checkout);
  await mkdir(join(checkout,'node_modules'));await mkdir(join(checkout,'.local'));await writeFile(join(checkout,'.local','state.json'),'preserved');
  await writeFile(join(bin,'npm'),'#!/bin/sh\nprintf "%s\\n" "$*" >> "$UPDATE_TEST_LOG"\n',{mode:0o700});
  const probe=net.createServer();await new Promise(r=>probe.listen(0,'127.0.0.1',r));const port=probe.address().port;await new Promise(r=>probe.close(r));
  const options={cwd:checkout,env:{...process.env,PATH:`${bin}:${process.env.PATH}`,UPDATE_TEST_LOG:log,PORT:String(port)}};
  await writeFile(join(seed,'version.txt'),'two');await git(seed,'commit','-am','Update');await git(seed,'push');
  await execute('bash',['scripts/update-local.sh','staging'],options);
  assert.equal(await readFile(join(checkout,'version.txt'),'utf8'),'two');
  assert.equal(await readFile(join(checkout,'.local','state.json'),'utf8'),'preserved');
  assert.equal(await readFile(log,'utf8'),'run build\nstart\n');
  await writeFile(join(checkout,'version.txt'),'my edits');
  await assert.rejects(execute('bash',['scripts/update-local.sh','staging'],options),error=>error.stderr.includes('Save or commit'));
  assert.equal(await readFile(join(checkout,'version.txt'),'utf8'),'my edits');
  await assert.rejects(execute('bash',['scripts/update-local.sh','../../bad'],options),error=>error.stderr.includes('Choose staging'));
});
